# 常见广告/水印标记
AD_PATTERNS = [
    "点击查看", "点击展开", "展开全文", "全文阅读", "阅读全文",
    "责任编辑", "本文来源", "来源：网络", "广告", "推广",
    "扫码关注", "关注公众号", "下载APP", "登录后查看",
]

_HTML_TAG_RE = re.compile(r"<[^>]*>")
_ENTITY_MAP = {
    "&nbsp;": " ",
    "&amp;": "&",
    "&quot;": '"',
    "&#39;": "'",
    "&lt;": "<",
    "&gt;": ">",
}


def strip_html_tags(text: str) -> str:
    if not text:
        return ""
    result = _HTML_TAG_RE.sub("", text)
    for entity, char in _ENTITY_MAP.items():
        result = result.replace(entity, char)
    return result


def normalize_whitespace(text: str) -> str:
    if not text:
        return ""
    result = re.sub(r"[\t\r\n]+", " ", text)
    result = re.sub(r"[ \t]+", " ", result)
    result = re.sub(r" {2,}", " ", result)
    return result.strip()


def remove_bom(text: str) -> str:
    if not text:
        return ""
    return text.lstrip("﻿")


def to_simplified(text: str) -> str:
    """繁体转简体（本地映射）"""
    if not text:
        return ""
    return "".join(T2S_MAP.get(ch, ch) for ch in text)


def remove_ads(text: str) -> str:
    """去除常见广告/水印标记"""
    if not text:
        return ""
    result = text
    for ad in AD_PATTERNS:
        result = result.replace(ad, "")
    return result


def clean_content(text: str) -> str:
    """对应 TS cleanContent（额外增加去广告与繁转简）"""
    if not text:
        return ""
    result = text
    result = strip_html_tags(result)
    result = remove_bom(result)
    result = normalize_whitespace(result)
    result = remove_ads(result)
    result = to_simplified(result)
    result = re.sub(r"[ \t]+([，。！？；：])", r"\1", result)
    result = re.sub(r"([，。！？；：])([^ \"])", r"\1\2", result)
    return result.strip()


def truncate_summary(text: str, max_len: int = 100) -> str:
    """对应 TS truncateSummary"""
    if not text:
        return ""
    if len(text) <= max_len:
        return text
    return text[:max_len] + "..."
