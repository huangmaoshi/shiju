export const TRAD_TABLE_SIZE = Object.keys(TRAD_TO_SIMPL).length;

/**
 * 判断是否含有繁体字（任意字符在繁简映射表中即视为含繁体）
 */
export function containsTraditionalChinese(text: string): boolean {
  if (!text) return false;
  for (let i = 0; i < text.length; i++) {
    if (TRAD_TO_SIMPL[text[i]]) return true;
  }
  return false;
}

/**
 * 繁体 -> 简体（逐字映射）。
 * 未收录的字符原样返回；因此简体中文输入输出一致。
 */
export function tradToSimpl(text: string): string {
  if (!text) return '';
  let out = '';
  for (let i = 0; i < text.length; i++) {
    const ch = text[i];
    out += TRAD_TO_SIMPL[ch] || ch;
  }
  return out;
}
