const TRAD_TO_SIMPL: Record<string, string> = {};
for (const line of TRAD_SIMPL_PAIRS) {
  const tokens = line.trim().split(/\s+/);
  for (const tok of tokens) {
    if (tok.length < 2) continue;
    // 每个 token 是成对的 "萬万"，支持 1-1 映射
    for (let i = 0; i < tok.length - 1; i += 2) {
      const t = tok[i];
      const s = tok[i + 1];
      if (!TRAD_TO_SIMPL[t]) TRAD_TO_SIMPL[t] = s;
    }
  }
}

